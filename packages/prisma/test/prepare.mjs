// Builds the SQLite test schema from the shipped models (schema/rbac.prisma),
// generates the client into test/generated and recreates the throwaway SQLite file test/.tmp/test.db
// (the file is deleted and re-pushed, so no `--force-reset` is needed).
// Usage: node test/prepare.mjs [--generate-only]
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const tmp = join(here, '.tmp')
const schemaPath = join(tmp, 'schema.prisma')

const header = `// GENERATED by test/prepare.mjs — do not edit.
generator client {
  provider = "prisma-client-js"
  output   = "../generated"
}

datasource db {
  provider = "sqlite"
  url      = "file:./test.db"
}

`

mkdirSync(tmp, { recursive: true })
writeFileSync(schemaPath, header + readFileSync(join(root, 'schema', 'rbac.prisma'), 'utf8'))

const prisma = (...args) =>
  execFileSync('prisma', [...args, '--schema', schemaPath], {
    cwd: root,
    stdio: 'inherit',
    shell: process.platform === 'win32',
    env: { ...process.env, PRISMA_HIDE_UPDATE_MESSAGE: '1' },
  })

prisma('generate')
if (!process.argv.includes('--generate-only')) {
  for (const f of ['test.db', 'test.db-journal']) rmSync(join(tmp, f), { force: true })
  prisma('db', 'push', '--skip-generate')
}
