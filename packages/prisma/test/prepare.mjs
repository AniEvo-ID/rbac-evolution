// Builds the test schemas from the shipped models (schema/rbac-expiry.prisma and schema/rbac.prisma) and generates one client per provider:
// - SQLite     → test/generated        (always pushed: throwaway file test/.tmp/test.db, deleted and re-pushed)
// - SQLite, 1.1 models (no `expiresAt`) → test/generated-legacy (always pushed: test/.tmp/legacy.db)
// - PostgreSQL → test/generated-pg     (pushed only when PG_URL is set)
// - MySQL      → test/generated-mysql  (pushed only when MYSQL_URL is set)
// The PostgreSQL / MySQL clients are always generated (typecheck needs them); generating needs no database.
// Pushes to a real server go to a dedicated database (see TEST_DATABASE) and reset it first.
//
// It works with every supported Prisma version, the one installed decides (the CI `peers` job swaps it):
// - Prisma 5.12 / 6: the `prisma-client-js` generator, the datasource `url` in the schema, the Rust engine.
// - Prisma 7: the `prisma-client` generator (ESM TypeScript, imported from `<output>/client`) for every client
//   but the 1.1 one, which keeps the deprecated `prisma-client-js` so both generators are covered. No `url` in
//   the schema (a Prisma config file per target, test/.tmp/*.config.mjs, holds it), and every client is built with
//   a driver adapter (`@prisma/adapter-better-sqlite3`, `@prisma/adapter-pg`, `@prisma/adapter-mariadb`).
// Either way, each output directory gets a `connect.ts` that the tests import: it re-exports `PrismaClient` and
// `Prisma`, and exports `connect(url)`, which builds a client for that database the way the version wants
// (plus `databaseUrl`, the throwaway file, for the SQLite clients).
// Usage: node test/prepare.mjs [--generate-only]
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const tmp = join(here, '.tmp')
/** The shipped models with expiry (schema/rbac-expiry.prisma). */
const models = readFileSync(join(root, 'schema', 'rbac-expiry.prisma'), 'utf8')
/** The shipped default models (schema/rbac.prisma): the schema of a 1.1 install, without `expiresAt`. */
const legacyModels = readFileSync(join(root, 'schema', 'rbac.prisma'), 'utf8')
const generateOnly = process.argv.includes('--generate-only')

const require = createRequire(join(root, 'package.json'))
const prismaVersion = require('prisma/package.json').version
const clientVersion = require('@prisma/client/package.json').version
const major = Number(prismaVersion.split('.')[0])
if (Number(clientVersion.split('.')[0]) !== major) {
  throw new Error(`[prepare] prisma ${prismaVersion} and @prisma/client ${clientVersion} must be the same major.`)
}
/** Prisma 7+: no Rust engine, driver adapters, no `url` in the schema, the `prisma-client` generator. */
const v7 = major >= 7
console.log(`[prepare] Prisma ${prismaVersion}${v7 ? ' (driver adapters)' : ''}`)

/** Keep in sync with test/servers.test.ts. */
const TEST_DATABASE = 'rbac_evolution_prisma_test'
const withDatabase = (url, database) => {
  const u = new URL(url)
  u.pathname = `/${database}`
  return u.toString()
}

const sqliteUrl = (db) => `file:${join(tmp, db)}`

const targets = [
  { file: 'schema.prisma', provider: 'sqlite', output: 'generated', db: 'test.db' },
  { file: 'schema.legacy.prisma', provider: 'sqlite', output: 'generated-legacy', db: 'legacy.db', legacy: true },
  { file: 'schema.pg.prisma', provider: 'postgresql', output: 'generated-pg', env: 'PG_URL' },
  { file: 'schema.mysql.prisma', provider: 'mysql', output: 'generated-mysql', env: 'MYSQL_URL' },
]

/** `connect(url)` per provider on Prisma 7: the driver adapter. */
const adapters = {
  sqlite: {
    import: `import { PrismaBetterSqlite3 } from '@prisma/adapter-better-sqlite3'`,
    create: `new PrismaBetterSqlite3({ url })`,
  },
  postgresql: {
    import: `import { PrismaPg } from '@prisma/adapter-pg'`,
    create: `new PrismaPg({ connectionString: url })`,
  },
  mysql: {
    // The MariaDB driver also talks to MySQL. MySQL 8's default auth (caching_sha2_password) over a plain
    // connection needs the server's public key.
    import: `import { PrismaMariaDb } from '@prisma/adapter-mariadb'`,
    create: `(() => {
    const u = new URL(url)
    return new PrismaMariaDb({
      host: u.hostname,
      port: Number(u.port || 3306),
      user: decodeURIComponent(u.username),
      password: decodeURIComponent(u.password),
      database: u.pathname.slice(1),
      allowPublicKeyRetrieval: true,
    })
  })()`,
  },
}

/** Contents of `<output>/connect.ts`. */
function connectModule(target, jsGenerator) {
  const header = '// GENERATED by test/prepare.mjs — do not edit.\n'
  const footer =
    target.db === undefined ? '' : `\n/** The throwaway SQLite file. */\nexport const databaseUrl = ${JSON.stringify(sqliteUrl(target.db))}\n`
  // `prisma-client-js` writes `index.js` / `index.d.ts`; `prisma-client` writes `client.ts`.
  const entry = jsGenerator ? './index' : './client'
  if (!v7) {
    return `${header}import { PrismaClient } from '${entry}'
export { Prisma, PrismaClient } from '${entry}'

export const connect = (url: string) => new PrismaClient({ datasourceUrl: url })
${footer}`
  }
  const adapter = adapters[target.provider]
  return `${header}${adapter.import}
import { PrismaClient } from '${entry}'
export { Prisma, PrismaClient } from '${entry}'

export const connect = (url: string) => new PrismaClient({ adapter: ${adapter.create} })
${footer}`
}

mkdirSync(tmp, { recursive: true })

for (const target of targets) {
  const schemaPath = join(tmp, target.file)
  // On 7, the 1.1 client keeps the deprecated generator, so a `prisma-client-js` client is tested too.
  const jsGenerator = !v7 || target.legacy === true
  const url = target.env === undefined ? `"${sqliteUrl(target.db)}"` : `env("${target.env}")`
  writeFileSync(
    schemaPath,
    `// GENERATED by test/prepare.mjs — do not edit.
generator client {
  provider = "${jsGenerator ? 'prisma-client-js' : 'prisma-client'}"
  output   = "../${target.output}"
}

datasource db {
  provider = "${target.provider}"${v7 ? '' : `\n  url      = ${url}`}
}

${target.legacy ? legacyModels : models}`,
  )

  const serverUrl = target.env === undefined ? undefined : process.env[target.env]
  const testUrl = serverUrl ? withDatabase(serverUrl, TEST_DATABASE) : undefined
  // Prisma 7 reads the datasource URL from a Prisma config file, not from the schema (and `db push --url` only
  // exists in later 7.x releases). One config per target, with the URL when there is a database to push to.
  const configArgs = []
  if (v7) {
    const pushUrl = target.db === undefined ? testUrl : sqliteUrl(target.db)
    const configPath = join(tmp, target.file.replace(/\.prisma$/, '.config.mjs'))
    writeFileSync(
      configPath,
      `// GENERATED by test/prepare.mjs — do not edit.
export default ${JSON.stringify({ schema: target.file, ...(pushUrl ? { datasource: { url: pushUrl } } : {}) }, null, 2)}
`,
    )
    configArgs.push('--config', configPath)
  }
  const prisma = (...args) =>
    execFileSync('prisma', [...args, '--schema', schemaPath, ...configArgs], {
      cwd: root,
      stdio: 'inherit',
      shell: process.platform === 'win32',
      env: {
        ...process.env,
        PRISMA_HIDE_UPDATE_MESSAGE: '1',
        ...(testUrl ? { [target.env]: testUrl } : {}),
      },
    })

  const outputDir = join(here, target.output)
  rmSync(outputDir, { recursive: true, force: true })
  prisma('generate')
  writeFileSync(join(outputDir, 'connect.ts'), connectModule(target, jsGenerator))
  if (generateOnly) continue

  // Prisma 7 removed `--skip-generate`: `db push` no longer generates.
  const push = (...flags) => prisma('db', 'push', ...(v7 ? [] : ['--skip-generate']), ...flags)
  if (target.provider === 'sqlite') {
    for (const f of [target.db, `${target.db}-journal`]) rmSync(join(tmp, f), { force: true })
    push()
  } else if (testUrl) {
    push('--force-reset', '--accept-data-loss')
  } else {
    console.log(`[prepare] ${target.env} not set: skipping the ${target.provider} database (its suite will be skipped).`)
  }
}
