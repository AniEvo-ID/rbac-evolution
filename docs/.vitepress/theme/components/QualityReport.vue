<script setup lang="ts">
/** Renders the CI test report (docs/public/reports/unit.json, written by scripts/test-report.mjs). */
import { withBase } from 'vitepress'
import { computed, onMounted, ref } from 'vue'

interface Coverage {
  lines: number | null
  branches: number | null
  functions: number | null
  statements: number | null
}
interface PackageReport {
  name: string
  version: string
  ok: boolean
  tests: { total: number; passed: number; failed: number; skipped: number }
  files: number
  durationMs: number
  coverage: Coverage
}
interface UnitReport {
  generatedAt: string
  commit: string
  runUrl: string | null
  databases: { postgres: boolean; mysql: boolean; mongodb: boolean }
  totals: { total: number; passed: number; failed: number; skipped: number }
  ok: boolean
  packages: PackageReport[]
}

const report = ref<UnitReport | null>(null)
const state = ref<'loading' | 'ready' | 'missing'>('loading')

onMounted(async () => {
  try {
    const res = await fetch(withBase('/reports/unit.json'), { cache: 'no-store' })
    if (!res.ok) throw new Error(String(res.status))
    report.value = (await res.json()) as UnitReport
    state.value = 'ready'
  } catch {
    state.value = 'missing'
  }
})

const avg = (key: keyof Coverage) =>
  computed(() => {
    const values = (report.value?.packages ?? []).map((p) => p.coverage[key]).filter((v): v is number => v !== null)
    return values.length ? values.reduce((a, b) => a + b, 0) / values.length : null
  })
const avgLines = avg('lines')
const avgBranches = avg('branches')
const fmt = (v: number | null) => (v === null ? '—' : `${v.toFixed(1)}%`)
const level = (v: number | null) => (v === null ? '' : v >= 90 ? 'good' : v >= 75 ? 'ok' : 'low')
const short = (name: string) => name.replace('@anievo-id/rbac-evolution-', '').replace('@anievo-id/rbac-evolution', 'core')
const commitUrl = computed(() => (report.value ? `https://github.com/AniEvo-ID/rbac-evolution/commit/${report.value.commit}` : ''))
const when = computed(() => (report.value ? new Date(report.value.generatedAt).toLocaleString() : ''))
</script>

<template>
  <div class="quality">
    <p v-if="state === 'loading'" class="note">Loading the latest report…</p>
    <p v-else-if="state === 'missing'" class="note">
      No report has been published yet. It is generated by CI on every push to <code>main</code>.
    </p>
    <template v-else-if="report">
      <div class="status" :class="report.ok ? 'pass' : 'fail'">
        <span class="badge">{{ report.ok ? 'ALL SUITES PASSING' : 'FAILURES' }}</span>
        <span>
          Commit <a :href="commitUrl">{{ report.commit.slice(0, 7) }}</a> · {{ when }}
          <template v-if="report.runUrl"> · <a :href="report.runUrl">CI run</a></template>
        </span>
      </div>

      <div class="cards">
        <div class="card"><span class="num">{{ report.totals.passed }}</span><span class="lbl">tests passed</span></div>
        <div class="card" :class="{ bad: report.totals.failed > 0 }">
          <span class="num">{{ report.totals.failed }}</span><span class="lbl">failed</span>
        </div>
        <div class="card"><span class="num">{{ report.totals.skipped }}</span><span class="lbl">skipped</span></div>
        <div class="card"><span class="num">{{ fmt(avgLines) }}</span><span class="lbl">avg. line coverage</span></div>
        <div class="card"><span class="num">{{ fmt(avgBranches) }}</span><span class="lbl">avg. branch coverage</span></div>
      </div>

      <p class="dbs">
        Real databases in this run:
        <span :class="{ on: report.databases.postgres }">PostgreSQL</span>
        <span :class="{ on: report.databases.mysql }">MySQL</span>
        <span :class="{ on: report.databases.mongodb }">MongoDB</span>
      </p>

      <div class="table-wrap">
        <table>
          <thead>
            <tr>
              <th>Package</th>
              <th>Tests</th>
              <th>Skipped</th>
              <th>Lines</th>
              <th>Branches</th>
              <th>Functions</th>
              <th>Time</th>
            </tr>
          </thead>
          <tbody>
            <tr v-for="p in report.packages" :key="p.name">
              <td>
                <span class="dot" :class="p.ok ? 'pass' : 'fail'" :aria-label="p.ok ? 'passing' : 'failing'" />
                <a :href="`https://www.npmjs.com/package/${p.name}`">{{ short(p.name) }}</a>
                <small>{{ p.version }}</small>
              </td>
              <td>{{ p.tests.passed }}/{{ p.tests.total - p.tests.skipped }}</td>
              <td>{{ p.tests.skipped || '—' }}</td>
              <td v-for="k in ['lines', 'branches', 'functions'] as const" :key="k">
                <span class="bar" :class="level(p.coverage[k])">
                  <i :style="{ width: `${p.coverage[k] ?? 0}%` }" />
                </span>
                {{ fmt(p.coverage[k]) }}
              </td>
              <td>{{ (p.durationMs / 1000).toFixed(1) }}s</td>
            </tr>
          </tbody>
        </table>
      </div>
      <p class="note">
        Skipped tests are database suites that need a server (<code>PG_URL</code>, <code>MYSQL_URL</code>,
        <code>MONGO_URL</code>). Coverage counts each package's <code>src/</code> only.
      </p>
    </template>
  </div>
</template>

