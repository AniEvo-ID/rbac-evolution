#!/usr/bin/env node
// Lists every public export of every package entry point (values and types), read from the built `.d.ts` files.
//
//   pnpm build && node scripts/list-exports.mjs            # prints markdown to stdout
//   node scripts/list-exports.mjs --json                   # machine-readable output
//
// Used for the 1.0 API freeze (planning/01-api-freeze.md). Run it after `pnpm build`.
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(join(root, 'packages/core/package.json'))
const ts = require('typescript')

const asJson = process.argv.includes('--json')

/** Finds the `types` file of an `exports` entry, preferring the ESM condition. */
function typesOf(entry) {
  if (typeof entry === 'string') return entry.endsWith('.d.ts') ? entry : null
  if (!entry || typeof entry !== 'object') return null
  if (typeof entry.types === 'string') return entry.types
  for (const key of ['import', 'default', 'require']) {
    const found = typesOf(entry[key])
    if (found) return found
  }
  return null
}

function kindOf(symbol, checker) {
  const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol
  const f = target.flags
  if (f & ts.SymbolFlags.Class) return 'class'
  if (f & ts.SymbolFlags.Function) return 'function'
  if (f & ts.SymbolFlags.Enum) return 'enum'
  if (f & ts.SymbolFlags.Variable) return 'const'
  if (f & ts.SymbolFlags.Interface) return 'interface'
  if (f & ts.SymbolFlags.TypeAlias) return 'type'
  if (f & ts.SymbolFlags.Namespace || f & ts.SymbolFlags.ValueModule) return 'namespace'
  return 'other'
}

function isInternal(symbol, checker) {
  const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol
  return target.getJsDocTags(checker).some((tag) => tag.name === 'internal')
}

function isDeprecated(symbol, checker) {
  const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol
  return target.getJsDocTags(checker).some((tag) => tag.name === 'deprecated')
}

/** Public class members still marked `@internal` (reachable by users even though the docs hide them). */
function internalMembers(symbol, checker) {
  const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol
  if (!(target.flags & ts.SymbolFlags.Class) && !(target.flags & ts.SymbolFlags.Interface)) return []
  const out = []
  for (const member of target.members?.values() ?? []) {
    const decl = member.declarations?.[0]
    if (!decl) continue
    const modifiers = ts.getCombinedModifierFlags(decl)
    if (modifiers & (ts.ModifierFlags.Private | ts.ModifierFlags.Protected)) continue
    if (member.name.startsWith('#') || member.name.startsWith('__')) continue
    if (member.getJsDocTags(checker).some((tag) => tag.name === 'internal')) out.push(member.name)
  }
  return out.sort()
}

const packages = []
for (const dir of readdirSync(join(root, 'packages')).sort()) {
  const pkgPath = join(root, 'packages', dir, 'package.json')
  if (!existsSync(pkgPath)) continue
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
  const entries = []
  for (const [subpath, entry] of Object.entries(pkg.exports ?? {})) {
    if (subpath === './package.json') continue
    const types = typesOf(entry)
    if (!types) {
      entries.push({ subpath, file: typeof entry === 'string' ? entry : null, exports: null })
      continue
    }
    const file = join(root, 'packages', dir, types)
    if (!existsSync(file)) {
      console.error(`Missing ${file}. Run \`pnpm build\` first.`)
      process.exit(1)
    }
    const program = ts.createProgram([file], { skipLibCheck: true, noEmit: true, allowJs: false })
    const checker = program.getTypeChecker()
    const source = program.getSourceFile(file)
    const moduleSymbol = checker.getSymbolAtLocation(source)
    const exports = (moduleSymbol ? checker.getExportsOfModule(moduleSymbol) : [])
      .map((symbol) => ({
        name: symbol.name,
        kind: kindOf(symbol, checker),
        internal: isInternal(symbol, checker),
        deprecated: isDeprecated(symbol, checker),
        internalMembers: internalMembers(symbol, checker),
      }))
      .sort((a, b) => a.name.localeCompare(b.name))
    entries.push({ subpath, file: types, exports })
  }
  packages.push({ dir, name: pkg.name, version: pkg.version, entries })
}

if (asJson) {
  process.stdout.write(JSON.stringify(packages, null, 2) + '\n')
  process.exit(0)
}

const VALUE_KINDS = new Set(['class', 'function', 'enum', 'const', 'namespace'])
const lines = []
lines.push('<!-- Generated by scripts/list-exports.mjs. Regenerate the tables, keep the Decision column. -->')
for (const pkg of packages) {
  lines.push('', `## ${pkg.name}`, '')
  for (const entry of pkg.entries) {
    const specifier = entry.subpath === '.' ? pkg.name : `${pkg.name}/${entry.subpath.slice(2)}`
    if (!entry.exports) {
      lines.push(`### \`${specifier}\``, '', `Static file \`${entry.file}\`.`, '')
      continue
    }
    const values = entry.exports.filter((e) => VALUE_KINDS.has(e.kind)).length
    lines.push(
      `### \`${specifier}\``,
      '',
      `${entry.exports.length} exports (${values} values, ${entry.exports.length - values} types).`,
      '',
      '| Export | Kind | Notes | Decision |',
      '| --- | --- | --- | --- |',
    )
    for (const e of entry.exports) {
      const notes = []
      if (e.internal) notes.push('`@internal`')
      if (e.deprecated) notes.push('`@deprecated`')
      if (e.internalMembers.length) notes.push(`${e.internalMembers.length} public \`@internal\` members: ${e.internalMembers.map((m) => `\`${m}\``).join(', ')}`)
      lines.push(`| \`${e.name}\` | ${e.kind} | ${notes.join('; ')} | |`)
    }
    lines.push('')
  }
}
process.stdout.write(lines.join('\n') + '\n')
